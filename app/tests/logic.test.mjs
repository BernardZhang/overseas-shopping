import assert from 'node:assert/strict'
import { products } from '../src/data.ts'
import { filterProducts, parseCart, cartReducer, subtotal } from '../src/logic.ts'
const names = list => list.map(p => p.id)
assert.equal(products.length, 12)
assert.equal(new Set(products.map(p => p.id)).size, 12)
assert.deepEqual(names(filterProducts(products, '  VASE  ', 'Home', 'under', 'featured')), ['vase'])
assert.equal(filterProducts(products, 'vase', 'Travel', 'all', 'featured').length, 0)
assert.equal(filterProducts(products, 'nonexistent', 'All', 'all', 'featured').length, 0)
const middle = filterProducts(products, '', 'All', 'middle', 'ascending')
assert.equal(middle[0].priceCents, 5000)
assert.equal(middle.at(-1).priceCents, 10000)
assert.ok(!filterProducts(products, '', 'All', 'under', 'featured').some(p => p.priceCents === 5000))
assert.ok(!filterProducts(products, '', 'All', 'over', 'featured').some(p => p.priceCents === 10000))
const original = names(products)
assert.equal(filterProducts(products, '', 'All', 'all', 'ascending')[0].id, 'notebook')
assert.equal(filterProducts(products, '', 'All', 'all', 'descending')[0].id, 'lamp')
assert.deepEqual(names(products), original)
const ties = [{...products[0],featuredRank:5},{...products[0],id:'tie',featuredRank:2}]
assert.equal(filterProducts(ties, '', 'All', 'all', 'ascending')[0].id, 'tie')
let cart = cartReducer({}, {type:'add',id:'vase'})
cart = cartReducer(cart, {type:'add',id:'vase'})
cart = cartReducer(cart, {type:'add',id:'mug'})
assert.deepEqual(cart, {vase:2,mug:1})
assert.equal(subtotal(cart), 12400)
for(let i=0;i<15;i++)cart=cartReducer(cart,{type:'add',id:'vase'})
assert.equal(cart.vase,10)
cart=cartReducer(cart,{type:'decrease',id:'mug'})
assert.equal(cart.mug,1)
cart=cartReducer(cart,{type:'remove',id:'vase'})
assert.deepEqual(cart,{mug:1})
assert.deepEqual(cartReducer(cart,{type:'add',id:'unknown'}),cart)
for (const raw of [null,'broken','null','[]','{}','{"version":2,"items":{"vase":1}}'])assert.deepEqual(parseCart(raw),{})
assert.deepEqual(parseCart(JSON.stringify({version:1,items:{vase:2,mug:0,tote:11,lamp:1.5,unknown:1,clock:'2'}})),{vase:2})
assert.deepEqual(parseCart(JSON.stringify({version:1,items:{vase:10,mug:1}})),{vase:10,mug:1})
console.log('PASS: catalog filters, price boundaries, stable sorting, cart limits, integer subtotal, persistence validation')
